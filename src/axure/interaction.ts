/* Normalization                                                              */
/* -------------------------------------------------------------------------- */

/**
 * Axure event name → trigger.
 *
 * Keys are matched case- and separator-insensitively, so `onClick`, `onclick`, `on-click` and
 * `Click` all resolve. Anything unrecognized becomes `unknown` with the original preserved by
 * the caller, which is the honest outcome for a name we do not have a rule for.
 */
const TRIGGER_RULES: ReadonlyArray<readonly [RegExp, InteractionTrigger]> = [
  [/^(on)?(click|tap)$/, 'click'],
  [/^(on)?(dbl|double)(click|tap)$/, 'double-click'],
  [/^(on)?(contextmenu|rightclick)$/, 'context-menu'],
  [/^(on)?(mouseenter|mouseover|hover)$/, 'mouse-enter'],
  [/^(on)?(mouseleave|mouseout)$/, 'mouse-leave'],
  [/^(on)?(mousedown|pointerdown|touchstart)$/, 'mouse-down'],
  [/^(on)?(mouseup|pointerup|touchend)$/, 'mouse-up'],
  [/^(on)?(mousemove|pointermove|touchmove)$/, 'mouse-move'],
  [/^(on)?(focus|focusin)$/, 'focus'],
  [/^(on)?(blur|focusout)$/, 'blur'],
  [/^(on)?(keydown)$/, 'key-down'],
  [/^(on)?(keyup)$/, 'key-up'],
  [/^(on)?(textchange|change|input|keypress)$/, 'text-change'],
  [/^(on)?(selectionchange|select)$/, 'selection-change'],
  [/^(on)?(checkedchange|check)$/, 'checked-change'],
  [/^(on)?(pageload|load|ready)$/, 'page-load'],
  [/^(on)?(windowload)$/, 'load'],
  [/^(on)?(resize|windowresize)$/, 'page-resize'],
  [/^(on)?(scroll|windowscroll)$/, 'page-scroll'],
  [/^(on)?(swipe|swipeleft|swiperight|swipeup|swipedown)$/, 'swipe'],
  [/^(on)?(longpress|longtap|pressandhold)$/, 'long-press'],
];

/** Normalize a raw name to a comparison key: lowercase, letters and digits only. */
function normalizeKey(name: string): string {
  // Punctuation is stripped rather than replaced, because Axure display names contain slashes and
  // spaces that carry no meaning: "Set Selected/Checked" must match `setselectedchecked`.
  return name.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/**
 * Normalize a raw event name to a trigger, defaulting to `unknown`.
 */
export function normalizeTrigger(rawEvent: Raw): InteractionTrigger {
  const name = str(rawEvent);
  if (!name) return 'unknown';
  const key = normalizeKey(name);
  for (const [pattern, trigger] of TRIGGER_RULES) {
    if (pattern.test(key)) return trigger;
  }
  return 'unknown';
}

/**
 * Axure action name → normalized kind.
 *
 * The live deployment reports `{ action: 'setFunction', displayName: 'Set Selected/Checked',
 * description: 'Set is selected of This equal to "true"' }`, so both the internal `action` token
 * and the human `displayName` are candidate type names. An unrecognized name becomes `other` and
 * the caller preserves the original in `rawType`, so a future Axure action appears as `other` with
 * its real name attached instead of being silently mislabeled.
 */
const ACTION_RULES: ReadonlyArray<readonly [RegExp, InteractionActionKind]> = [
  // Internal Axure action tokens observed in the wild.
  [/^(navigate|pagelink|linkto|gotopage|openpage)$/, 'navigate'],
  [/^(openlink|openurl|url|link)$/, 'open-url'],
  [/^(setpanelstate|setpanel|setpanelbyname)$/, 'set-panel-state'],
  [/^(setpanelstateback|panelstateback|previouspanelstate)$/, 'set-panel-state-back'],
  [/^(show|showelement|showwidget|visibilityshow)$/, 'show'],
  [/^(hide|hideelement|hidewidget|visibilityhide)$/, 'hide'],
  [/^(togglevisibility|toggle)$/, 'toggle-visibility'],
  [/^(settext|settextvalue|text|setfunctiontext)$/, 'set-text'],
  [/^(setvalue|value|setfieldvalue|setfunctionvalue)$/, 'set-value'],
  [/^(setselected|selected|setcheckstate|setselectedchecked)$/, 'set-selected'],
  [/^(setchecked|checked)$/, 'set-checked'],
  [/^(focus|setfocus)$/, 'focus'],
  [/^(expand|collapse|expandcollapse|expandcollapsepanel|togglepanel)$/, 'expand-collapse'],
  [/^(move|moveby|moveto|setlocation)$/, 'move'],
  [/^(rotate|setrotation)$/, 'rotate'],
  [/^(setopacity|opacity|settransparency)$/, 'set-opacity'],
  [/^(scrollto|scrolltoview)$/, 'scroll-to'],
  [/^(fireevent|triggerevent|raiseevent)$/, 'fire-event'],
  [/^(wait|delay|pause)$/, 'wait'],
  // Display names, which read better and cover actions whose internal token is opaque.
  [/^(setselectedchecked)$/, 'set-selected'],
  [/^(setpanelstate\(.*\))$/, 'set-panel-state'],
  [/^(openlinkin.*)$/, 'open-url'],
  [/^(settextonwidget)$/, 'set-text'],
];

/** Normalize a raw action name to a kind, defaulting to `other`. */
export function normalizeActionKind(rawType: Raw): InteractionActionKind {
  const name = str(rawType);
  if (!name) return 'other';
  const key = normalizeKey(name);
  for (const [pattern, kind] of ACTION_RULES) {
    if (pattern.test(key)) return kind;
  }
  return 'other';
}

