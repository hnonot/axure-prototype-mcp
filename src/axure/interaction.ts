/**
 * Interaction recognition — the pure reasoning half.
 *
 * ## Why this module is separate from the browser code
 *
 * The hard part of this feature is not reading the page; it is deciding what is *known* versus
 * what is *guessed*, and the iteration is explicit that a guess must never be presented as a
 * confirmed result. So the evidence model lives here as a pure, dependency-free module:
 *
 * - no `playwright`, no DOM, no I/O;
 * - input is already-decoded plain data, output is typed `InteractionFact` records;
 * - every rule is exercisable by `scripts/test-interaction.mjs` with fixtures, no browser.
 *
 * The browser side (`interaction-runtime.ts`) is then only responsible for *obtaining* the raw
 * data and reporting honestly when it could not.
 *
 * ## The invariant that enforces the requirement
 *
 * The API makes "a guess never carries actions" a type-level constraint rather than a
 * convention: {@link declaredInteraction} is the only function that can produce `branches`, and
 * {@link inferredInteraction} structurally cannot. There is no code path that attaches an action
 * to an inferred record, so it cannot happen by accident or by a later edit that forgets the
 * rule.
 *
 * ## Handling an unknown raw shape
 *
 * The exact property names Axure uses in its decoded page model are not yet confirmed against
 * the live deployment (see `.update/0.2.0/audit.md`). This module therefore never asserts a
 * schema: every field is read through a defensive accessor, anything unrecognized is preserved
 * verbatim in `rawType` / `rawTrigger`, and a normalization miss yields `other` / `unknown`
 * rather than invented meaning. That keeps the module correct under an unknown shape instead of
 * merely plausible.
 */

import type {
  InteractionAction,
  InteractionActionKind,
  InteractionBranch,
  InteractionCondition,
  InteractionFact,
  InteractionStats,
  InteractionTarget,
  InteractionTrigger,
} from '../types.js';

/* -------------------------------------------------------------------------- */
/* Defensive readers                                                          */
/* -------------------------------------------------------------------------- */

/** An unknown, unvalidated value from the page. */
export type Raw = unknown;

/** True for a non-null, non-array object. */
export function isRecord(value: Raw): value is Record<string, Raw> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Read the first present, non-empty value among `keys`.
 *
 * Axure's decoded model uses several naming conventions across versions and across
 * single-versus-multiple action forms, so every field is looked up by a list of candidates.
 */
function pick(source: Record<string, Raw>, ...keys: string[]): Raw {
  for (const key of keys) {
    const value = source[key];
    if (value !== undefined && value !== null && value !== '') return value;
  }
  return undefined;
}

/**
 * Decode the HTML entities Axure writes into its own labels.
 *
 * Measured payload: `description: 'Set is selected of This equal to &quot;true&quot;'`. The text is
 * generated by Axure's editor, so it is escaped for HTML; leaving the entities in place makes the
 * output harder to read and would let a consumer mistake `&quot;` for real content.
 */
function unescapeEntities(value: string | undefined): string | undefined {
  if (!value) return value;
  return value
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&');
}

/** Read a string field, trimmed and entity-decoded; returns `undefined` rather than `''`. */
function str(value: Raw): string | undefined {
  if (typeof value === 'string') {
    const trimmed = value.trim();
    return trimmed.length ? trimmed : undefined;
  }
  if (typeof value === 'number' && Number.isFinite(value)) return String(value);
  return undefined;
}

/** Read a string field intended for display, with entities decoded. */
function displayStr(value: Raw): string | undefined {
  return unescapeEntities(str(value));
}

/** Read a finite integer field. */
function int(value: Raw): number | undefined {
  if (typeof value === 'number' && Number.isInteger(value)) return value;
  if (typeof value === 'string' && /^-?\d+$/.test(value.trim())) return Number.parseInt(value.trim(), 10);
  return undefined;
}

/** Coerce to an array without inventing elements. */
function arr(value: Raw): Raw[] {
  if (Array.isArray(value)) return value;
  if (value === undefined || value === null) return [];
  return [value];
}

