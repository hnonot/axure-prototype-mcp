/**
 * Read the widget ids an action targets.
 *
 * Axure stores targets under several names depending on the action, and sometimes as a single
 * value rather than a list. Confirmed payloads use `targetIds`; `setPanelState` addresses panels
 * through `panelsToStates[].panelPath`; link actions carry a `target`/`pageId`; and expression-based
 * actions name their target through the `expr` tree.
 */
function readTargetIds(action: Record<string, Raw>): string[] {
  const candidates = [
    pick(action, 'targetIds', 'targets', 'targetId', 'target'),
    pick(action, 'objectIds', 'objectId', 'elementIds', 'elementId'),
    pick(action, 'widgetIds', 'widgetId'),
  ];
  const ids: string[] = [];
  const push = (value: Raw): void => {
    const id = str(value);
    if (id && !ids.includes(id)) ids.push(id);
  };
  for (const candidate of candidates) {
    for (const entry of arr(candidate)) {
      // `target` is sometimes an object describing the destination rather than an id.
      if (isRecord(entry)) {
        push(pick(entry, 'targetId', 'id', 'pageId', 'pageName'));
        continue;
      }
      push(entry);
    }
  }

  // Panel-state actions name their panel through a hash in `panelsToStates[].panelPath`. That hash
  // is only meaningful inside the model, so it is *not* reported as a target: the reader resolves
  // it to a DOM id and the analyzer attaches that as `panelId`. Emitting the hash as well would
  // present an unresolvable reference as though it were a target on this page.
  // (Nothing to do here for panels; see the loop below for other target shapes.)

  // `expr.subExprs[].arguments[]` holds `pathLiteral` node references. These are the *widget* a
  // set-function action addresses, e.g. `SetCheckState(is selected of This, "true")`.
  const expr = action.expr;
  if (isRecord(expr)) {
    for (const node of collectExprNodes(expr)) {
      if (!isRecord(node)) continue;
      if (node.exprType !== 'pathLiteral' && node.exprType !== 'elementPathLiteral') continue;
      // Only a non-`This` path names another widget; `isThis` means the widget being observed.
      if (node.isThis === true) continue;
      push(pick(node, 'path', 'value', 'name', 'id'));
    }
  }

  return ids;
}

/**
 * Read the panel state an action switches to.
 *
 * Confirmed payload: `panelsToStates: [{ panelPath: [hash], stateInfo: { stateNumber: 2,
 * stateValue: { value: '1' } } }]`.
 *
 * The **1-based `stateNumber`** is the field that actually distinguishes the cases: for a two-state
 * panel, `展开` reports `stateNumber: 2` and `收起` reports `stateNumber: 1`, while `stateValue` is
 * `"1"` in both. Reporting `stateValue` therefore made expand and collapse indistinguishable —
 * a bug caught by reading the real output rather than by trusting the field name.
 *
 * `state` is reported **zero-based** so it aligns with the page map's 0-based active panel state,
 * and the raw `stateNumber` is kept beside it.
 */
function readState(action: Record<string, Raw>): { state?: number; stateNumber?: number } {
  for (const panel of arr(pick(action, 'panelsToStates', 'panelStates', 'panels'))) {
    if (!isRecord(panel)) continue;
    const info = pick(panel, 'stateInfo', 'state');
    if (isRecord(info)) {
      const number = int(pick(info, 'stateNumber', 'index'));
      if (number !== undefined) return { state: Math.max(0, number - 1), stateNumber: number };
      const stateValue = info.stateValue;
      const authored = isRecord(stateValue) ? int(pick(stateValue, 'value')) : undefined;
      if (authored !== undefined) return { state: Math.max(0, authored - 1), stateNumber: authored };
    }
  }
  const fallback = int(pick(action, 'stateIndex', 'state', 'panelState', 'targetState'));
  return fallback === undefined ? {} : { state: fallback, stateNumber: fallback };
}


/** Depth-first collect every expression node in an Axure `expr` tree. */
function collectExprNodes(root: Raw): Raw[] {
  const nodes: Raw[] = [];
  const seen = new Set<Raw>();
  const walk = (value: Raw, depth: number): void => {
    if (depth > 12 || !value || typeof value !== 'object' || seen.has(value)) return;
    seen.add(value);
    if (Array.isArray(value)) {
      for (const item of value) walk(item, depth + 1);
      return;
    }
    const record = value as Record<string, Raw>;
    if (record.exprType !== undefined) nodes.push(record);
    for (const key of Object.keys(record)) {
      if (key === 'parent') continue;
      walk(record[key], depth + 1);
    }
  };
  walk(root, 0);
  return nodes;
}

/** Build the target list for one action, marking resolution only when it was measured. */
function buildTargets(action: Record<string, Raw>, resolve?: (widgetId: string) => boolean): InteractionTarget[] | undefined {
  const targets: InteractionTarget[] = [];

  for (const widgetId of readTargetIds(action)) {
    const target: InteractionTarget = { widgetId };
    if (resolve) target.resolved = resolve(widgetId);
    targets.push(target);
  }

  // Navigation targets name a page rather than a widget.
  const pageId = str(pick(action, 'pageId', 'targetPageId', 'destinationPageId'));
  const pageName = str(pick(action, 'pageName', 'targetPageName', 'destinationPageName'));
  if (pageId || pageName) {
    targets.push({
      ...(pageId ? { pageId } : {}),
      ...(pageName ? { pageName } : {}),
    });
  }

  // An unresolvable target the model still labeled should be reported, not dropped. The action's
  // own `description` is deliberately *not* used here: it is a sentence about the action, not a
  // target, and treating it as one produced a bogus `label` alongside the real `value`.
  if (targets.length === 0) {
    const label = displayStr(pick(action, 'targetName', 'targetLabel'));
    if (label) targets.push({ label });
  }

  return targets.length ? targets : undefined;
}

/** Decode one action, preserving its raw type. */
export function decodeAction(action: Raw, order: number, resolve?: (widgetId: string) => boolean): InteractionAction {
  if (!isRecord(action)) {
    return { kind: 'other', order };
  }
  // Confirmed payloads carry the internal token in `action` and the readable label in
  // `displayName`; the readable one is preferred for classification because it is stable across
  // actions whose internal token is opaque.
  const displayName = displayStr(pick(action, 'displayName'));
  const internalType = str(pick(action, 'action', 'type', 'actionType', 'friendlyType', 'name'));
  const rawType = displayName ?? internalType;
  const decoded: InteractionAction = { kind: normalizeActionKind(rawType), order };
  if (displayName) decoded.rawType = displayName;
  else if (internalType) decoded.rawType = internalType;
  // Keep the internal token when it differs, so nothing is lost in normalization.
  if (internalType && displayName && internalType !== displayName) decoded.internalType = internalType;

  const targets = buildTargets(action, resolve);
  if (targets) decoded.targets = targets;

  const state = readState(action);
  if (state.state !== undefined) decoded.state = state.state;
  if (state.stateNumber !== undefined) decoded.stateNumber = state.stateNumber;

  // The human description is the most reliable value source ("...equal to \"true\""), and it is
  // also kept verbatim so nothing the model said is lost.
  const description = cleanDescription(pick(action, 'description', 'actionInfoDescription'));
  if (description) decoded.description = description;
  const value =
    displayStr(pick(action, 'value', 'text', 'textValue', 'newValue', 'expression')) ??
    extractQuotedValue(description);
  if (value) decoded.value = value;

  const delayMs = int(pick(action, 'waitTime', 'delay', 'delayMs', 'duration'));
  if (delayMs !== undefined) decoded.delayMs = delayMs;

  return decoded;
}

/**
 * Normalize an Axure action description for display.
 *
 * Confirmed payload: `"Set 会员中心 to&nbsp; to 展开 push/pull widgets below "` — it contains
 * non-breaking spaces and doubled separators left by Axure's own template. Collapsing whitespace and
 * decoding entities makes it readable without changing its meaning.
 */
function cleanDescription(value: Raw): string | undefined {
  const decoded = displayStr(value);
  if (!decoded) return undefined;
  const cleaned = decoded.replace(/\s+/g, ' ').replace(/\s+to\s+to\s+/i, ' to ').trim();
  return cleaned.length ? cleaned : undefined;
}

/**
 * Pull the quoted operand out of an Axure action description.
 *
 * The model writes `Set is selected of This equal to "true"` (HTML-escaped, already decoded by
 * {@link displayStr} before this runs), which is how the value a set-function assigns is recorded.
 * Only the quoted part is used.
 */
function extractQuotedValue(description: string | undefined): string | undefined {
  if (!description) return undefined;
  const match = /"([^"]*)"/.exec(description);
  return match?.[1];
}

/** Decode one condition, keeping only what the model actually stated. */
function decodeCondition(condition: Raw, conditionString?: string): InteractionCondition | undefined {
  if (!isRecord(condition)) {
    const description = str(condition);
    if (description) return { description };
    return conditionString ? { description: conditionString } : undefined;
  }
  const decoded: InteractionCondition = {};
  const target = str(pick(condition, 'target', 'leftOperand', 'lhs', 'objectName', 'element'));
  const operator = str(pick(condition, 'operator', 'comparison', 'op', 'comparisonType'));
  const value = str(pick(condition, 'value', 'rightOperand', 'rhs', 'expectedValue'));
  const description = str(pick(condition, 'description', 'text', 'friendlyText', 'label'));
  if (target) decoded.target = target;
  if (operator) decoded.operator = operator;
  if (value) decoded.value = value;
  // `conditionString` is Axure's own plain-language rendering ("if is selected of This equals
  // false") and is preserved verbatim, which is more useful to a reader than a partial parse.
  if (conditionString) decoded.conditionString = conditionString;
  else if (description) decoded.description = description;
  return Object.keys(decoded).length ? decoded : undefined;
}

/**
 * Decode a `declared` interaction's branches.
 *
 * Walks the two shapes Axure uses — a nested `interactionMap[event][caseIndex]` and a flat
 * `event -> cases` list — without asserting which one is present.
 */
export function decodeBranches(rawEvent: Raw, resolve?: (widgetId: string) => boolean): InteractionBranch[] {
  const branches: InteractionBranch[] = [];

  // Either a list of cases, or a single case object.
  const caseList = arr(pick(isRecord(rawEvent) ? rawEvent : {}, 'cases', 'caseList', 'case') ?? rawEvent);

  caseList.forEach((caseEntry, index) => {
    if (!isRecord(caseEntry)) return;
    const branch: InteractionBranch = { actions: [] };

    const name = str(pick(caseEntry, 'name', 'caseName', 'description', 'label'));
    if (name) branch.name = name;
    else branch.name = `Case ${index + 1}`;

    const conditions: InteractionCondition[] = [];
    const conditionString = displayStr(pick(caseEntry, 'conditionString', 'conditionDescription'));
    const rawConditions = arr(pick(caseEntry, 'conditions', 'condition', 'expressionList'));
    for (const rawCondition of rawConditions) {
      const condition = decodeCondition(rawCondition, conditionString);
      if (condition) conditions.push(condition);
    }
    if (conditions.length) branch.conditions = conditions;

    for (const rawAction of arr(pick(caseEntry, 'actions', 'actionList', 'action'))) {
      branch.actions.push(decodeAction(rawAction, branch.actions.length, resolve));
    }

    branches.push(branch);
  });

  return branches;
}

