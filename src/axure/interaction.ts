/** Order facts by widget then trigger so output is stable across runs. */
export function sortInteractions(facts: InteractionFact[]): InteractionFact[] {
  return [...facts].sort((a, b) => {
    if (a.widgetId !== b.widgetId) return numericId(a.widgetId) - numericId(b.widgetId);
    if (a.trigger !== b.trigger) return a.trigger.localeCompare(b.trigger);
    if (a.confidence !== b.confidence) return a.confidence.localeCompare(b.confidence);
    return (a.rawTrigger ?? '').localeCompare(b.rawTrigger ?? '');
  });
}

/** Numeric part of an Axure widget id, for a natural `u2 < u10` ordering. */
function numericId(widgetId: string): number {
  const match = /(\d+)/.exec(widgetId);
  const digits = match?.[1];
  return digits === undefined ? Number.MAX_SAFE_INTEGER : Number.parseInt(digits, 10);
}

/** Compute the aggregate statistics for a result. */
export function summarize(facts: InteractionFact[], widgetCount: number): InteractionStats {
  const byConfidence: InteractionStats['byConfidence'] = { declared: 0, observed: 0, inferred: 0 };
  const byActionKind: Record<string, number> = {};
  const widgets = new Set<string>();
  let branches = 0;

  for (const fact of facts) {
    byConfidence[fact.confidence] += 1;
    widgets.add(fact.widgetId);
    for (const branch of fact.branches ?? []) {
      branches += 1;
      for (const action of branch.actions) {
        byActionKind[action.kind] = (byActionKind[action.kind] ?? 0) + 1;
      }
    }
  }

  return {
    widgets: widgetCount,
    widgetsWithInteractions: widgets.size,
    byConfidence,
    byActionKind,
    branches,
  };
}

/**
 * Drop interactions the caller does not want to see.
 *
 * Filtering happens on the *data*, so an `inferred`-only view is a mechanical choice for a
 * consumer rather than a re-reading of prose.
 */
export function filterInteractions(
  facts: InteractionFact[],
  options: { confidences?: ReadonlyArray<InteractionFact['confidence']>; widgetIds?: ReadonlyArray<string>; triggers?: ReadonlyArray<InteractionTrigger> },
): InteractionFact[] {
  const confidences = options.confidences ? new Set(options.confidences) : undefined;
  const widgetIds = options.widgetIds ? new Set(options.widgetIds) : undefined;
  const triggers = options.triggers ? new Set(options.triggers) : undefined;

  return facts.filter((fact) => {
    if (confidences && !confidences.has(fact.confidence)) return false;
    if (widgetIds && !widgetIds.has(fact.widgetId)) return false;
    if (triggers && !triggers.has(fact.trigger)) return false;
    return true;
  });
}
