/* Fact constructors — the evidence-level contract                            */
/* -------------------------------------------------------------------------- */

/** Shared inputs for both constructors. */
export interface FactIdentity {
  widgetRef: string;
  widgetId: string;
  widgetLabel?: string;
  rawTrigger?: string;
}

/**
 * Build a **declared** fact: the project model states this interaction.
 *
 * This is the only constructor that can attach branches, so a fact with actions is by
 * construction a fact whose actions were read from the model.
 */
export function declaredInteraction(
  identity: FactIdentity,
  branchSource: Raw,
  options?: { resolve?: (widgetId: string) => boolean },
): InteractionFact {
  const branches = decodeBranches(branchSource, options?.resolve);
  const fact: InteractionFact = {
    widgetRef: identity.widgetRef,
    widgetId: identity.widgetId,
    trigger: normalizeTrigger(identity.rawTrigger),
    confidence: 'declared',
    source: 'axure-project-model',
  };
  if (identity.widgetLabel) fact.widgetLabel = identity.widgetLabel;
  if (identity.rawTrigger) fact.rawTrigger = identity.rawTrigger;
  if (branches.length) fact.branches = branches;
  return fact;
}

/**
 * Build an **observed** fact: the page was triggered and this is what changed.
 *
 * Same shape as `declared` but a different evidence level, because an observation covers only
 * the branch that ran and says nothing about the alternatives.
 */
export function observedInteraction(identity: FactIdentity, actions: InteractionAction[]): InteractionFact {
  const fact: InteractionFact = {
    widgetRef: identity.widgetRef,
    widgetId: identity.widgetId,
    trigger: normalizeTrigger(identity.rawTrigger),
    confidence: 'observed',
    source: 'trigger-observation',
  };
  if (identity.widgetLabel) fact.widgetLabel = identity.widgetLabel;
  if (identity.rawTrigger) fact.rawTrigger = identity.rawTrigger;
  if (actions.length) fact.branches = [{ name: 'observed', actions }];
  return fact;
}

/**
 * Build an **inferred** fact: the widget looks interactive, nothing more is known.
 *
 * Structurally cannot carry branches — there is no parameter that accepts actions — which is
 * what makes "a guess is never presented as a confirmed action" enforceable rather than
 * merely intended. `inferredReason` is required so every guess states its basis.
 */
export function inferredInteraction(
  identity: FactIdentity,
  trigger: InteractionTrigger,
  inferredReason: string,
): InteractionFact {
  const fact: InteractionFact = {
    widgetRef: identity.widgetRef,
    widgetId: identity.widgetId,
    trigger,
    confidence: 'inferred',
    source: 'dom-observation',
    inferredReason,
  };
  if (identity.widgetLabel) fact.widgetLabel = identity.widgetLabel;
  if (identity.rawTrigger) fact.rawTrigger = identity.rawTrigger;
  return fact;
}

